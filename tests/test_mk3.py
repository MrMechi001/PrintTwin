class Clock:
    """printer.py's clock, moved by hand (time.time / sleep / strftime as the module uses them)."""
    def __init__(self, t=1_800_000_000.0):
        self.t = t

    def time(self):
        return self.t

    def sleep(self, s):
        self.t += s

    def strftime(self, f):
        return time.strftime(f)


def offline_printer(tp, pi=True, **cfg):
    """A PrusaLinkPrinter that never polls: its job and toolpath set by hand (nothing to load)."""
    d = Path(tempfile.mkdtemp(prefix="printtwin-mk3off-"))
    TMP.append(d)
    pr = P.PrusaLinkPrinter({"id": "t", "host": "127.0.0.1:9", "api_key": "x", **cfg}, d, d)
    pr.pi, pr.online = pi, True
    pr.job = {"id": 1, "display_name": "t.gcode", "name": "t.gcode", "download": "/x", "size": 1, "m_timestamp": 1}
    pr.tp, pr.tracker, pr.tp_cache_key = tp, Tracker(tp), "1_1"
    return pr


def in_layer(tp, p):
    """How far into its layer the place p is (0 = at the layer's start)."""
    ls = tp.layer_start + [tp.count]
    i = max(0, bisect_right(ls, p) - 1)
    return (p - ls[i]) / max(1, ls[min(i + 1, len(ls) - 1)] - ls[i])


def digest_offline():
    # RFC 2617 section 3.5: MD5, qop=auth - a known answer
    d = PL._Digest("Mufasa", "Circle Of Life")
    d.take('Digest realm="testrealm@host.com", qop="auth,auth-int", nonce="dcd98b7102dd2f0e8b11d0f600bfb0c093", '
           'opaque="5ccc069c403ebaf9f0171e9517f40e41"')
    d.cnonce = "0a4f113b"
    h = d.header("GET", "/dir/index.html")
    f = {k: q or v for k, q, v in PL._PARAM.findall(h[7:])}
    check("digest: RFC 2617 known answer (MD5, qop auth, nc 1)", f.get("response") == "6629fae49393a05397450978507c4ef1"
          and f.get("nc") == "00000001" and f.get("opaque") == "5ccc069c403ebaf9f0171e9517f40e41", h)
    h2 = d.header("GET", "/dir/index.html")
    check("digest: nc counts up per request", 'nc=00000002' in h2)
    # MD5-sess as PrusaLink (PoorWSGI) wants it, checked by the simulator's independent server code
    srv = SIM.DigestServer("maker", "s3cret pass", ttl=60)
    d = PL._Digest("maker", "s3cret pass")
    d.take(srv.challenge())
    uri = PL.url_path("/api/files/local/PrusaLink gcodes/MK3S part.gcode/raw")
    h = d.header("GET", uri)
    check("digest: MD5-sess accepted by PrusaLink's rules (opaque + algorithm echoed exactly)",
          srv.check(h, "GET", uri) == "ok" and "algorithm=MD5-sess" in h, h)
    bad = PL._Digest("maker", "nope")
    bad.take(srv.challenge())
    check("digest: a wrong password is refused", srv.check(bad.header("GET", uri), "GET", uri) == "refused")
    ch = PL.digest_challenge('Digest realm="Administrator",qop="auth",algorithm="MD5-sess",nonce="ab",opaque="cd",stale=true')
    check("digest: challenge parsed (no spaces, stale)", ch == {"realm": "Administrator", "qop": "auth",
          "algorithm": "MD5-sess", "nonce": "ab", "opaque": "cd", "stale": "true"}, str(ch))
    check("digest: no digest challenge -> None", PL.digest_challenge('Basic realm="x"') is None)
    c = PL.PrusaLink("127.0.0.1:9", "", user="maker", password="pw")
    check("digest: no empty X-Api-Key sent", "X-api-key" not in c._request("/api/v1/status", None).headers)
    c = PL.PrusaLink("127.0.0.1:9", "KEY", user="maker", password="pw")
    check("an API key wins over user + password", c.digest is None and c._request("/x", None).headers.get("X-api-key") == "KEY")


