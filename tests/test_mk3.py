def truth(tp, t, layer_s=3.0):
    """Where the simulated print is t seconds in (same timeline as the simulator: layer by layer)."""
    ls, n = tp.layer_start, tp.count
    k = int(t / layer_s)
    if k >= len(ls):
        return n, len(ls) - 1
    end = ls[k + 1] if k + 1 < len(ls) else n
    return ls[k] + (t / layer_s - k) * (end - ls[k]), k


def pct_at(marks, seg):
    i = bisect_right([s for s, _ in marks], seg) - 1
    return marks[i][1] if i >= 0 else 0


def next_mark(marks, seg, n):
    for s, _ in marks:
        if s > seg:
            return s
    return n


def run_estimate(tp, stealth=False, hop=0.4, dur=54.0, layer_s=3.0):
    """Polls every 2 s (Z from the 2 s report, a z-hop in every third), estimate ticks every 0.5 s."""
    clock = Clock()
    P.time = clock
    pr = offline_printer(tp)
    t0 = clock.t
    marks = tp.silent_marks if stealth else tp.progress_marks
    total = len(tp.layer_z) * layer_s
    rows, k = [], 0
    try:
        while clock.t - t0 < dur:
            e = clock.t - t0
            if abs(e - 2.0 * k) < 1e-6:            # a status poll (the M155 report of this moment)
                seg, lay = truth(tp, e, layer_s)
                z = tp.layer_z[lay] + (hop if k % 3 == 1 else 0.0)
                pc = pct_at(marks, seg)
                rem = total * (1.15 if stealth else 1.0) * (1 - pc / 100)
                pr._on_status({"printer": {"state": "PRINTING", "axis_z": round(z, 2), "temp_nozzle": 215.0},
                               "job": {"id": 1, "progress": float(pc), "time_remaining": int(rem)}})
                k += 1
            with pr.lock:
                pr._estimate_now(pr.tracker)
            seg, lay = truth(tp, clock.t - t0, layer_s)
            rows.append((seg, lay, pr.tracker.printed))
            clock.t += 0.5
    finally:
        P.time = time
    return rows, pr


def judge(rows, tp, marks, label):
    n = tp.count
    ls = tp.layer_start + [n]
    pr = [r[2] for r in rows]
    fwd = all(b >= a for a, b in zip(pr, pr[1:]))
    # never past what the printer reported: the next mark after the true place, and the true layer's end
    over = [(round(s), round(p)) for s, lay, p in rows if p > max(next_mark(marks, s, n), ls[lay + 1]) + 0.5]
    inside = [p for s, lay, p in rows[20:] if in_layer(tp, p) > 0.1]
    late = [s - p for s, lay, p in rows[20:]]
    check(f"estimate ({label}): only forward", fwd)
    check(f"estimate ({label}): never past the printer's next mark or its layer (z-hops don't count)", not over,
          f"{len(over)} times, e.g. {over[:3]}")
    check(f"estimate ({label}): moves on inside the layer, not only at layer starts", len(inside) > 0.4 * len(rows[20:]),
          f"{len(inside)} of {len(rows[20:])} ticks inside a layer")
    check(f"estimate ({label}): close behind the print (< 1 layer on average)",
          sum(late) / len(late) < (ls[1] - ls[0]), f"{sum(late) / len(late):.0f} segments behind, a layer is {ls[1] - ls[0]}")


def estimate_offline(tp):
    rows, pr = run_estimate(tp)
    judge(rows, tp, tp.progress_marks, "normal mode")
    check("estimate (normal mode): the P marks win the vote", pr._est.votes["P"] > pr._est.votes["Q"], str(pr._est.votes))
    snap = pr.snapshot()
    check("estimate: HUD says estimated (no metrics hint on a Pi)", snap["metrics"]["estimated"] is True
          and "hint" not in snap["metrics"] and snap["nozzle"] is not None)
    rows, pr = run_estimate(tp, stealth=True)
    judge(rows, tp, tp.silent_marks, "stealth mode")
    check("estimate (stealth mode): the Q marks win the vote", pr._est.votes["Q"] > pr._est.votes["P"], str(pr._est.votes))
    rows, _ = run_estimate(tp, hop=0.0)
    judge(rows, tp, tp.progress_marks, "no z-hops")
    # the start: heating / probing at 0 % moves through the first layers' heights - nothing printed yet
    clock = Clock()
    P.time = clock
    try:
        pr = offline_printer(tp)
        for z in (5.0, 0.2, 2.0, 1.0, 1.0, 1.0):
            pr._on_status({"printer": {"state": "PRINTING", "axis_z": z}, "job": {"id": 1, "progress": 0.0,
                                                                                  "time_remaining": 600}})
            clock.t += 2.0
            with pr.lock:
                pr._estimate_now(pr.tracker)
        check("estimate: 0 % with Z at a layer height (probing) - nothing printed", pr.tracker.printed == 0.0,
              f"{pr.tracker.printed}")
        # paused: time stands still
        pr = offline_printer(tp)
        at_pause = None
        for st in ("PRINTING", "PRINTING", "PAUSED", "PAUSED", "PAUSED", "PAUSED"):
            pr._on_status({"printer": {"state": st, "axis_z": 1.0}, "job": {"id": 1, "progress": 20.0,
                                                                             "time_remaining": 480}})
            with pr.lock:
                pr._estimate_now(pr.tracker)
            if st == "PAUSED" and at_pause is None:
                at_pause = pr.tracker.printed
            clock.t += 2.0
        check("estimate: paused - the place stands still", at_pause and pr.tracker.printed == at_pause
              and in_layer(tp, at_pause) > 0.1, f"{at_pause} -> {pr.tracker.printed}")
    finally:
        P.time = time


def noid_offline(tp):
    """A job without id (PrusaLink just restarted): the file decides, not the missing id."""
    clock = Clock()
    P.time = clock
    calls, cur_id = [], [None]
    files = {"name": "a.gcode", "display_name": "a.gcode", "size": 10, "m_timestamp": 5,
             "refs": {"download": "/api/files/local/PrusaLink gcodes/a.gcode/raw"}}

    class Fake:
        def get_json(self, path):
            calls.append(path)
            job = {"state": "PRINTING", "file": dict(files)}
            if cur_id[0] is not None:
                job["id"] = cur_id[0]
            return 200, job
    try:
        pr = offline_printer(tp)
        pr.job, pr.client = None, Fake()
        st = {"printer": {"state": "PRINTING"}, "job": {"progress": 10.0}}
        j1 = pr._current_job(st)
        pr.job = j1
        check("job without id: taken", j1 is not None and j1["id"] is None)
        files.update(name="b.gcode", display_name="b.gcode", size=20)
        check("job without id: the same id-less job for 10 s", pr._current_job(st) is None)
        clock.t += P.NOID_CHECK_S + 1
        j2 = pr._current_job(st)
        check("two id-less jobs with different files are two jobs", j2 is not None and j2["name"] == "b.gcode")
        pr.job = j2
        clock.t += P.NOID_CHECK_S + 1
        st2 = {"printer": {"state": "PRINTING"}, "job": {"progress": 12.0}}
        check("id-less, same file: the same print", pr._current_job(st2) is None)
        pr._current_job({"printer": {"state": "FINISHED"}, "job": {"progress": 100.0}})
        j3 = pr._current_job({"printer": {"state": "PRINTING"}, "job": {"progress": 0.0}})
        check("id-less, the same file printed again: a new print", j3 is not None and j3 is not j2)
        pr.job = j3
        files["refs"] = {"download": None}
        old_calls = len(calls)
        cur_id[0] = 7
        j4 = pr._current_job({"printer": {"state": "PRINTING"}, "job": {"id": 7, "progress": 1.0}})
        check("the id shows up later: no new job, the id adopted", j4 is None and pr.job["id"] == 7
              and len(calls) == old_calls + 1, f"{pr.job.get('id')}")
        check("SD-card job: not downloadable, says why", "SD card" in (pr._not_downloadable({"download": None}) or "")
              and pr._not_downloadable({"download": "/x"}) is None)
    finally:
        P.time = time


def version_offline(tp):
    """/api/version: Buddy has "printer"; PrusaLink on a Pi only "original" - "Unknown printer type"
    until it knows (asked again later), then "PrusaLink I3MK3S"."""
    clock = Clock()
    P.time = clock
    answers = [{"api": "0.9.0-legacy", "original": "Unknown printer type", "text": "PrusaLink 0.7.2"},
               {"api": "0.9.0-legacy", "original": "PrusaLink I3MK3S", "text": "PrusaLink 0.7.2"}]
    asked = []

    class Fake:
        def get_json(self, path):
            if path == "/api/version":
                asked.append(path)
                return 200, answers.pop(0) if len(answers) > 1 else answers[0]
            return 200, {"printer": {"state": "READY"}, "storage": [{"path": "/local"}, {"path": "/sdcard"}]}
    try:
        pr = offline_printer(tp, pi=False)
        pr.client, pr.printer_type = Fake(), None
        pr._on_online()
        check("Pi, 'Unknown printer type': PrusaLink on a Pi, model from the job meanwhile",
              pr.pi and pr.printer_type is None and pr.snapshot()["model_source"] in ("job", "unknown"))
        data = pr._fetch_status()
        check("state READY and the storage list are a valid status", isinstance(data, dict) and len(asked) == 1)
        clock.t += P.TYPE_RETRY_S + 1
        pr._fetch_status()
        check("asked again later: 1.3.1 -> mk3s", pr.printer_type == "1.3.1" and pr.snapshot()["model"] == "mk3s"
              and len(asked) == 2, f"{pr.printer_type} after {len(asked)} questions")
        clock.t += P.TYPE_RETRY_S + 1
        pr._fetch_status()
        check("then not asked any more", len(asked) == 2)
        answers[:] = [{"api": "2.0.0", "printer": "1.4.0", "text": "PrusaLink"}]
        pr = offline_printer(tp, pi=False)
        pr.client, pr.printer_type = Fake(), None
        pr._on_online()
        check("Buddy (MK4): not a Pi, its type from 'printer'", not pr.pi and pr.printer_type == "1.4.0")
    finally:
        P.time = time


def metrics_offline():
    """The MK4 path: with UDP metrics the tracker follows them exactly as before - no estimate."""
    tp = load_file(ROOT / "tests" / "fixtures" / "sample.bgcode")
    pr = offline_printer(tp, pi=False)
    ref = Tracker(tp)
    snap = pr.snapshot()
    check("MK4 before any metrics: estimated, with the hint to turn them on",
          snap["metrics"]["estimated"] is True and "metrics" in snap["metrics"].get("hint", ""))
    msg, t_us, out = 0, 1_000_000, []
    first = tp.layer_start[2]
    for j in range(first, first + 400, 3):
        b = 3 * j
        sd = tp.line_off[min(j + 6, tp.count - 1)]
        x, y, z = (round(v, 3) for v in (tp.end[b], tp.end[b + 1], tp.end[b + 2]))     # as the datagram has them
        msg += 1
        t_us += 15_000
        dg = (f"<14>1 - 10:9c:70:00:00:01 buddy - - - msg={msg},tm={t_us},v=4 "
              f"sdpos v={sd}i 0\npos_x v={x:.3f} 10\npos_y v={y:.3f} 10\npos_z v={z:.3f} 10\n").encode()
        pr.on_datagram(dg)
        ref.feed_sdpos(sd)
        ref.feed_pos(x, y, z)
        out.append((pr.tracker.printed, ref.printed))
    check("MK4 with metrics: printed follows the live position exactly as before",
          all(a == b for a, b in out) and out[-1][0] > first, f"{out[-1]}")
    snap = pr.snapshot()
    check("MK4 with metrics: not estimated, no hint", pr.estimated is False and snap["metrics"]["estimated"] is False
          and "hint" not in snap["metrics"])
    # metrics stall: the layer fallback from Z as before (not the estimate)
    pr.last_pos_wall = pr.last_sdpos_wall = time.time() - 10
    ref2 = Tracker(tp)
    pr.tracker = Tracker(tp)
    st = {"printer": {"state": "PRINTING", "axis_z": tp.layer_z[5]}, "job": {"id": 1, "progress": 40.0, "time_remaining": 99}}
    pr._on_status(st)
    ref2.from_axis_z(tp.layer_z[5], 40.0)
    check("MK4, metrics stalled: Z fallback as before", pr.tracker.printed == ref2.printed == tp.layer_start[5],
          f"{pr.tracker.printed} vs {ref2.printed}")


