def e2e_sd_down_noid(job: Path):
    """503 first (serial link down), then an SD-card job without hand-over, its id missing at first."""
    sim = Sim(job, "--pi", "--sd", "--no-printer", "5", "--no-id", "12")
    try:
        st = sim.wait(lambda s: s.get("note"), timeout=15)
        check("503: 'PrusaLink is up, the printer is not connected' instead of offline / login errors",
              bool(st) and st.get("note") == "PrusaLink is up, the printer is not connected" and not st.get("online"),
              str(st and st.get("note")))
        st = sim.wait(lambda s: s.get("online") and (s.get("loading") or {}).get("message"), timeout=20)
        msg = ((st or {}).get("loading") or {}).get("message") or ""
        check("SD-card job, no hand-over: says so (no download possible)",
              "SD card" in msg and "hand-over" in msg and (st.get("job") or {}).get("name") == job.name, msg)
        check("SD-card job: no old model shown", st.get("toolpath_key") is None)
        time.sleep(10)                                 # the id appears at 12 s
        st = sim.state()
        stats = get(f"{sim.printer}/sim/stats")
        jobs = stats["requests"].get("/api/v1/job", 0)
        check("SD-card job: no retry storm (no download, /api/v1/job asked only a few times)",
              not [p for p in stats["requests"] if p.endswith("/raw")] and jobs <= 4, f"{jobs} job requests")
        check("the job id shows up late: still the same job", st.get("job", {}).get("id") == 1, str(st.get("job")))
    finally:
        out = sim.stop()
    news = [ln for ln in out.splitlines() if re.search(r" sim job (None|\d+): ", ln)]
    check("the job id shows up late: no second job", len(news) == 1, str(news))
    ok = out.count("PrusaLink is up, the printer is not connected") == 1 and "Traceback" not in out
    check("503 logged once, no traceback", ok, "" if ok else out[-600:])


def e2e_wrong_password(job: Path):
    sim = Sim(job, "--pi", "--digest", "maker:right")
    try:
        cfg = sim.dir / "config.toml"
        sim.wait(lambda s: s.get("online"), timeout=15)        # the simulator's own bridge logs in fine
        text = cfg.read_text(encoding="utf-8").replace('password = "right"', 'password = "wrong"')
        port = free_port()
        cfg2 = sim.dir / "config2.toml"
        cfg2.write_text(text.replace(f"port = {sim.port}", f"port = {port}")
                        .replace(f"listen_port = {sim.pport + 1}", f"listen_port = {free_port()}"), encoding="utf-8")
        b = subprocess.Popen([sys.executable, "-I", "-u", str(ROOT / "run.py"), "--config", str(cfg2)],
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        try:
            st, t0 = None, time.time()
            while time.time() - t0 < 15:
                try:
                    st = get(f"http://127.0.0.1:{port}/api/p/sim/state")
                    if st.get("note"):
                        break
                except OSError:
                    pass
                time.sleep(0.3)
            check("wrong password: the viewer says PrusaLink refused the login",
                  bool(st) and not st.get("online") and "refused the login" in (st.get("note") or ""), str(st and st.get("note")))
        finally:
            b.terminate()
            b.communicate(timeout=10)
    finally:
        sim.stop()


def e2e_mk4_metrics():
    """An MK4 (Buddy PrusaLink) that sends UDP metrics from the start: the live path, unchanged."""
    job = ROOT / "tests" / "fixtures" / "sample.bgcode"
    tp = load_file(job)
    sim = Sim(job, "--handover", layer="0.5", heat="6")      # 0 % until metrics flow: nothing to estimate
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    dest = ("127.0.0.1", sim.pport + 1)
    msg = [0]

    def send(sd, x, y, z):
        msg[0] += 1
        sock.sendto((f"<14>1 - 10:9c:70:00:00:01 buddy - - - msg={msg[0]},tm={msg[0] * 15000},v=4 "
                     f"sdpos v={sd}i 0\npos_x v={x:.3f} 10\npos_y v={y:.3f} 10\npos_z v={z:.3f} 10\n").encode(), dest)
    try:
        t0 = time.time()
        st = None
        while time.time() - t0 < 30:                  # parked, file position 0 - until the model is there
            send(0, 0.0, 200.0, 60.0)
            try:
                st = sim.state()
                if st.get("toolpath_complete") and st["metrics"].get("pos_age") is not None:
                    break
            except OSError:
                pass
            time.sleep(0.1)
        check("MK4: toolpath ready, metrics arriving", bool(st and st.get("toolpath_complete")))
        ref = Tracker(tp)
        ref.feed_sdpos(0)
        first = tp.layer_start[3]
        for j in range(first, first + 600, 4):
            b = 3 * j
            sd = tp.line_off[min(j + 6, tp.count - 1)]
            x, y, z = (round(v, 3) for v in (tp.end[b], tp.end[b + 1], tp.end[b + 2]))   # as the datagram has them
            send(sd, x, y, z)
            ref.feed_sdpos(sd)
            ref.feed_pos(x, y, z)
            time.sleep(0.01)
        time.sleep(0.5)
        st = sim.state()
        check("MK4 with metrics: printed exactly where the live position says (as before)",
              abs((st.get("printed") or 0) - round(ref.printed, 3)) < 1e-6, f"{st.get('printed')} vs {ref.printed:.3f}")
        check("MK4 with metrics: live, not estimated", st["metrics"]["estimated"] is False
              and st["metrics"]["pos_age"] is not None and st["metrics"]["pos_age"] < 3 and "hint" not in st["metrics"])
    finally:
        sock.close()
        out = sim.stop()
    check("MK4: 'metrics arrive' logged, no traceback", "metrics arrive: live position" in out and "Traceback" not in out)


