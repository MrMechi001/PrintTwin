def get(url, timeout=10):
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return json.loads(r.read())


class Sim:
    def __init__(self, job: Path, *extra, layer="3", heat="2"):
        self.port, self.pport = free_port(), free_port()
        self.dir = Path(tempfile.mkdtemp(prefix="printtwin-mk3-"))
        self.proc = subprocess.Popen([sys.executable, "-I", "-u", str(ROOT / "tools" / "sim_printer.py"), str(job),
                                      "--port", str(self.port), "--printer-port", str(self.pport), "--dir", str(self.dir),
                                      "--kbps", "400", "--heat", heat, "--layer", layer, *extra],
                                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        self.base = f"http://127.0.0.1:{self.port}"
        self.printer = f"http://127.0.0.1:{self.pport}"

    def state(self):
        return get(f"{self.base}/api/p/sim/state")

    def wait(self, cond, timeout=40.0):
        t0, st = time.time(), None
        while time.time() - t0 < timeout:
            try:
                st = self.state()
                if cond(st):
                    return st
            except OSError:
                pass
            time.sleep(0.25)
        return st

    def stop(self) -> str:
        self.proc.terminate()
        try:
            out = self.proc.communicate(timeout=10)[0].decode("utf-8", "replace")
        except subprocess.TimeoutExpired:
            self.proc.kill()
            out = self.proc.communicate()[0].decode("utf-8", "replace")
        shutil.rmtree(self.dir, ignore_errors=True)
        return out


def watch(sim, secs, tp, marks):
    """Sample the bridge's place and the simulator's truth for a while."""
    rows, t0 = [], time.time()
    while time.time() - t0 < secs:
        st, tr = sim.state(), get(f"{sim.printer}/sim/truth")
        if tr["state"] == "PRINTING" and tr["layer"] >= 0:
            rows.append((tr["seg"], tr["layer"], st.get("printed") or 0.0, st))
        time.sleep(0.5)
    n = tp.count
    ls = tp.layer_start + [n]
    pr = [r[2] for r in rows]
    over = [(round(s), round(p)) for s, lay, p, _ in rows if p > max(next_mark(marks, s, n), ls[lay + 1]) + 0.5]
    inside = [1 for s, lay, p, _ in rows if in_layer(tp, p) > 0.1]
    return rows, pr, over, inside


def e2e_digest_normal(job: Path, tp):
    sim = Sim(job, "--pi", "--digest", "maker:pass word", "--nonce-ttl", "3")
    try:
        st = sim.wait(lambda s: s.get("online") and s.get("printer_type"))
        check("MK3S: online through a digest login", bool(st and st.get("online")))
        check("MK3S: PrusaLink on a Pi detected - 'PrusaLink I3MK3S' -> 1.3.1 -> mk3s from the printer",
              st.get("printer_type") == "1.3.1" and st.get("model") == "mk3s" and st.get("model_source") == "printer",
              f"{st.get('printer_type')} {st.get('model')} {st.get('model_source')}")
        st = sim.wait(lambda s: s.get("toolpath_complete"))
        check("MK3S: job file downloaded from 'PrusaLink gcodes' (space in the path)",
              bool(st and st.get("toolpath_complete")) and st.get("toolpath_count") == tp.count,
              f"{st and st.get('toolpath_count')} segments")
        sim.wait(lambda s: (s.get("printed") or 0) > 0, timeout=20)
        rows, pr, over, inside = watch(sim, 16, tp, tp.progress_marks)
        check("MK3S: estimate moves forward, never back", len(pr) > 10 and pr[-1] > pr[0]
              and all(b >= a for a, b in zip(pr, pr[1:])), f"{pr[0]:.0f} -> {pr[-1]:.0f}" if pr else "no samples")
        check("MK3S: never past the printer's next mark or its layer (z-hops in the Z reports)", not over,
              f"{len(over)} of {len(rows)}, e.g. {over[:3]}")
        check("MK3S: moves on inside the reported layer", len(inside) > 0.3 * max(1, len(rows)),
              f"{len(inside)} of {len(rows)}")
        last = rows[-1][3] if rows else {}
        check("MK3S: HUD estimated, no X/Y, no metrics hint", last.get("metrics", {}).get("estimated") is True
              and last.get("axis_x") is None and "hint" not in last.get("metrics", {}))
        stats = get(f"{sim.printer}/sim/stats")
        dg = stats["digest"]
        check("MK3S: digest - logins ok, stale nonces renewed, nothing refused",
              dg["ok"] > 5 and dg["stale"] >= 1 and dg["refused"] == 0, str(dg))
        raw = [p for p in stats["requests"] if p.endswith("/raw")]
        check("MK3S: the download asked for the right path", raw == [f"/api/files/local/PrusaLink gcodes/{job.name}/raw"], str(raw))
        if not (ROOT / "web" / "models" / "mk3s.glb").exists():   # until the MK3S+ model is built
            listed = get(f"{sim.base}/api/models")["glb"]
            code = None
            try:
                urllib.request.urlopen(f"{sim.base}/models/mk3s.glb", timeout=10)
            except urllib.error.HTTPError as e:
                code = e.code
            check("no mk3s.glb yet: not offered to the viewer, a request gets 404 (printers.js falls back)",
                  "mk3s.glb" not in listed and code == 404, f"{listed} / HTTP {code}")
    finally:
        out = sim.stop()
    check("MK3S: no traceback", "Traceback" not in out, out[-600:] if "Traceback" in out else "")


