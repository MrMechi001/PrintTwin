def mk3s_gcode(layers=20, segs=60, k=1.6) -> bytes:
    """A small job in PrusaSlicer's MK3S style, written for this test: 0.2 mm layers, a z-hop of
    0.4 mm on every travel, "M73 P.. R.." (normal) and "M73 Q.. S.." (stealth) marks. Stealth mode
    is timed differently: its percent at segment i is 100 * (i / total) ** k."""
    total = layers * segs
    out = ["; generated by PrintTwin's tests in the style of PrusaSlicer's MK3S output", "",
           "M73 P0 R10", "M73 Q0 S12", 'M862.3 P "MK3S" ; printer model check', "G90", "M83",
           "M104 S215", "M140 S60", "M190 S60", "M109 S215", "G28 W ; home all without mesh bed level",
           "G80 ; mesh bed leveling", "G1 Z0.2 F720", "G1 Y-3.0 F1000.0 ; go outside print area",
           "G1 X60.0 E9.0 F1000.0 ; intro line", "G1 X100.0 E12.5 F1000.0 ; intro line", "G92 E0.0"]
    p_last = q_last = 0
    for lay in range(layers):
        z = 0.2 * (lay + 1)
        out += [";LAYER_CHANGE", f";Z:{z:.1f}", ";HEIGHT:0.2", "G1 E-.8 F2100", f"G1 Z{z + 0.4:.1f} F720",
                "G1 X120 Y100 F10800", f"G1 Z{z:.1f} F720", "G1 E.8 F1500", ";TYPE:External perimeter",
                ";WIDTH:0.45", "G1 F1200"]
        for j in range(segs):
            i = lay * segs + j
            pc, qc = int(100 * i / total), int(100 * (i / total) ** k)
            if pc != p_last:
                out.append(f"M73 P{pc} R{round(10 * (1 - pc / 100))}")
                p_last = pc
            if qc != q_last:
                out.append(f"M73 Q{qc} S{round(12 * (1 - qc / 100))}")
                q_last = qc
            if j == segs // 2:                     # a travel to the next island: retract, z-hop, back down
                out += ["G1 E-.8 F2100", f"G1 Z{z + 0.4:.1f} F720", "G1 X100 Y120 F10800", f"G1 Z{z:.1f} F720",
                        "G1 E.8 F1500"]
            a = 2 * math.pi * (j + 1) / segs
            out.append(f"G1 X{100 + 20 * math.cos(a):.3f} Y{100 + 20 * math.sin(a):.3f} E.02")
    out += ["M73 P100 R0", "M73 Q100 S0", f"G1 Z{0.2 * layers + 10:.1f} F720", "M104 S0", "M140 S0", "M84", "",
            "; filament_colour = #FF8000", "; nozzle_diameter = 0.4", "; printer_model = MK3S",
            "; retract_lift = 0.4", "; silent_mode = 1", ""]
    return "\n".join(out).encode()


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


