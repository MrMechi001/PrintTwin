"""Klipper printers via Moonraker, end to end: simulated Moonraker (tools/sim_moonraker.py) -> PrintTwin.

usage: python -I tests/test_moonraker.py
Checks the adapter (model, live tracking, progress) and the slicer pass-through for Klipper
(both upload routes, "upload and print" taken from PrintTwin's copy, only the slicer's calls
passed on, API key, a file Moonraker rewrites). No real printer needed.
"""
import json
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
failures = 0


def check(name, cond, detail=""):
    global failures
    print(("PASS " if cond else "FAIL ") + name + (f"  ({detail})" if detail else ""))
    failures += 0 if cond else 1


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def job_gcode(layers=24, tag="A") -> bytes:
    """A small Voron 2.4 job as PrusaSlicer writes it: Klipper G-code, PRINT_START, footer config."""
    out = ["; generated by PrusaSlicer 2.9.7 on 2026-11-07 at 12:00:00 UTC", f"; test job {tag}",
           "; thumbnail begin 300x300 20000"] + ["; " + "QUJDRA" * 13 for _ in range(250)] + [
           "; thumbnail end", "M73 P0 R10", "PRINT_START EXTRUDER=245 BED=100", "G90", "M83"]
    for k in range(layers):
        z = 0.2 * (k + 1)
        out += [";LAYER_CHANGE", f";Z:{z:.1f}", ";HEIGHT:0.2", f"G1 Z{z:.1f} F600", ";TYPE:External perimeter",
                "G1 X150 Y150 F9000"]
        for i in range(40):                   # a square spiral: many short moves, like real infill
            d = 2 + i
            out += [f"G1 X{150 + d} Y150 E0.05", f"G1 X{150 + d} Y{150 + d} E0.05",
                    f"G1 X150 Y{150 + d} E0.05", "G1 X150 Y150 E0.05"]
    out += ["PRINT_END", "; prusaslicer_config = begin", "; bed_shape = 0x0,350x0,350x350,0x350",
            "; gcode_flavor = klipper", "; printer_model = V2_350", "; prusaslicer_config = end", ""]
    return "\n".join(out).encode()


def get(url, headers=None):
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers or {}), timeout=15) as r:
        return r.status, json.loads(r.read() or b"null")


def call(url, method="GET", body=b"", headers=None):
    req = urllib.request.Request(url, data=body if method != "GET" else None, method=method, headers=headers or {})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.read()


def multipart(fields: dict, filename: str, data: bytes):
    b = "----printtwin-test-boundary"
    out = b""
    for k, v in fields.items():
        out += f'--{b}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'.encode()
    out += (f'--{b}\r\nContent-Disposition: form-data; name="file"; filename="{filename}"\r\n'
            f"Content-Type: application/octet-stream\r\n\r\n").encode() + data + f"\r\n--{b}--\r\n".encode()
    return out, {"Content-Type": f"multipart/form-data; boundary={b}"}


def start_sim(job: Path, *extra):
    port, pport = free_port(), free_port()
    proc = subprocess.Popen([sys.executable, "-I", "-u", str(ROOT / "tools" / "sim_moonraker.py"), str(job),
                             "--port", str(port), "--printer-port", str(pport), *extra],
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    return proc, f"http://127.0.0.1:{port}", f"http://127.0.0.1:{pport}"


def wait_state(base, cond, timeout=40):
    t0, st = time.time(), None
    while time.time() - t0 < timeout:
        try:
            st = get(f"{base}/api/p/sim/state")[1]
            if cond(st):
                return st
        except OSError:
            pass
        time.sleep(0.25)
    return st


def stop(proc) -> str:
    proc.terminate()
    try:
        return proc.communicate(timeout=10)[0].decode("utf-8", "replace")
    except subprocess.TimeoutExpired:
        proc.kill()
        return proc.communicate()[0].decode("utf-8", "replace")


def run_main(tmp: Path):
    job = tmp / "voron_cube.gcode"
    job.write_bytes(job_gcode())
    proc, base, printer = start_sim(job, "--qgl", "--duration", "10", "--heat", "2", "--kbps", "60")
    try:
        st = wait_state(base, lambda s: s.get("toolpath_complete"))
        check("job file from Moonraker, toolpath built", bool(st and st.get("toolpath_complete")),
              f"{st and st.get('toolpath_count')} segments")
        check("kind moonraker, Klipper corexy + quad gantry level",
              st.get("kind") == "moonraker" and st.get("printer_type") == "klipper/corexy+qgl", st.get("printer_type"))
        check("model from the job (PrusaSlicer V2_350): flying-gantry CoreXY",
              st.get("model") == "corexy_gantry" and st.get("model_source") == "job", f"{st.get('model')} {st.get('model_source')}")
        check("travel limits reported", (st.get("volume") or {}).get("max") == [350.0, 350.0, 330.0], str(st.get("volume")))

        st1 = wait_state(base, lambda s: (s.get("printed") or 0) > 200)
        rate = 0.0
        for _ in range(6):                    # the rate covers the last 2 s: wait for a moving window
            time.sleep(0.5)
            st2 = get(f"{base}/api/p/sim/state")[1]
            rate = max(rate, (st2.get("metrics") or {}).get("pos_rate") or 0)
        m = st2.get("metrics") or {}
        check("live nozzle tracked: progress moves on", (st2.get("printed") or 0) > (st1.get("printed") or 0) > 200,
              f"{st1.get('printed')} -> {st2.get('printed')}")
        check("file position in sync with the job file", (m.get("sync") or {}).get("ok") == 1.0, str(m.get("sync")))
        check("live position stream ~3-4 Hz", rate >= 2.5, str(rate))
        check("state, temperatures, progress, remaining time",
              st2.get("state") == "PRINTING" and (st2.get("temps") or {}).get("nozzle") == 265.0
              and 0 < (st2.get("progress") or 0) < 100 and st2.get("time_remaining") is not None,
              f"{st2.get('state')} {st2.get('progress')} % {st2.get('time_remaining')} s")
        sd = get(f"{base}/api/p/sim/toolpath.json")[1]
        check("nozzle Z in file coordinates (G-code offset removed)",
              abs((st2.get("axis_z") or 0) - round(st2.get("axis_z") or 0, 1)) < 0.011, str(st2.get("axis_z")))

        st = wait_state(base, lambda s: s.get("state") == "FINISHED", 30)
        check("print complete -> FINISHED, all printed", st.get("state") == "FINISHED"
              and st.get("printed") == sd["count"], f"{st.get('state')} {st.get('printed')}/{sd['count']}")

        # the slicer, through PrintTwin: Moonraker-native upload and print (PrusaSlicer "Klipper (via
        # Moonraker)", OrcaSlicer "Moonraker (Klipper)")
        code, body = call(f"{base}/p/sim/server/info")
        check("GET /p/sim/server/info (connection test) passes", code == 200 and b"klippy_state" in body, str(code))
        code, body = call(f"{base}/p/sim/server/files/roots")
        check("GET /p/sim/server/files/roots passes", code == 200 and b"gcodes" in body, str(code))
        job2 = job_gcode(layers=180, tag="B")
        body, hdr = multipart({"root": "gcodes", "print": "true"}, "second job.gcode", job2)
        old_key = get(f"{base}/api/p/sim/state")[1].get("toolpath_key")
        t0 = time.time()
        code, reply = call(f"{base}/p/sim/server/files/upload", "POST", body, hdr)
        r = json.loads(reply or b"{}")
        check("upload and print via /server/files/upload: Moonraker's 201 reply", code == 201
              and r.get("print_started") is True and r.get("item", {}).get("path") == "second job.gcode", f"{code} {r}")
        st = wait_state(base, lambda s: (s.get("job") or {}).get("name") == "second job.gcode"
                        and s.get("toolpath_key") != old_key and s.get("toolpath_complete"), 20)
        check("the new job's model comes at once (PrintTwin's copy, not the 60 KB/s download)",
              bool(st and st.get("toolpath_complete")) and time.time() - t0 < 3.0, f"{time.time() - t0:.1f} s")
        st = get(f"{base}/api/p/sim/state")[1]
        check("during PRINT_START (nozzle parked at Z 30 inside the 36 mm part, progress already > 0): "
              "nothing counts as printed", (st.get("printed") or 0) < 50 and (st.get("progress") or 0) > 0,
              f"printed {st.get('printed')}, {st.get('progress')} %")

        # OctoPrint-style upload (PrusaSlicer / OrcaSlicer host type OctoPrint), no print
        code, body = call(f"{base}/p/sim/api/version")
        check("GET /p/sim/api/version (OctoPrint emulation) passes", code == 200 and b"OctoPrint" in body, str(code))
        body, hdr = multipart({"print": "false", "path": "parts"}, "third.gcode", job_gcode(layers=4, tag="C"))
        code, reply = call(f"{base}/p/sim/api/files/local", "POST", body, hdr)
        check("upload via /api/files/local into a subfolder", code == 201
              and json.loads(reply).get("item", {}).get("path") == "parts/third.gcode", f"{code} {reply[:80]!r}")

        # uploads that must not reach Moonraker: into the config root (printer.cfg!) or out of gcodes
        b2 = "----printtwin-test-boundary"
        evil = [("root=config", {"root": "config"}, "printer.cfg"), ("root=CONFIG", {"root": "CONFIG"}, "printer.cfg"),
                ("two roots", {"root": "gcodes", "root ": "config"}, "x.cfg"),
                ("path ../", {"path": "../config"}, "printer.cfg"), ("name ../", {}, "../config/printer.cfg"),
                ("absolute path", {"path": "/home/pi/printer_data/config"}, "printer.cfg"),
                # names Moonraker's header parser decodes to ../ (RFC 2047 word, quoted-pair escape)
                ("encoded file name", {}, "=?utf-8?b?Li4vZ2NvZGVzX3B3bi9wd25lZC5nY29kZQ==?="),
                ("escaped file name", {}, r".\./gcodes_pwn.gcode")]
        for label, fields, fname in evil:
            body, hdr = multipart(fields, fname, b"[printer]\nkinematics: none\n")
            body = body.replace(b'name="root "', b'name="root"')           # a second root field
            code, _ = call(f"{base}/p/sim/server/files/upload", "POST", body, hdr)
            check(f"upload with {label} refused", code == 403, str(code))
        body = (f'--{b2}\r\nContent-Disposition: form-data; name=root\r\n\r\nconfig\r\n'
                f'--{b2}\r\nContent-Disposition: form-data; name="file"; filename="printer.cfg"\r\n\r\nX\r\n'
                f'--{b2}--\r\n').encode()
        code, _ = call(f"{base}/p/sim/server/files/upload", "POST", body,
                       {"Content-Type": f"multipart/form-data; boundary={b2}"})
        check("upload with an unquoted root field refused", code == 403, str(code))
        # parser tricks (second review): a "--boundary--" inside the file is data for Moonraker, not
        # the end of the form; boundaries Moonraker's email parser reads differently; two Content-Types
        bb = "BYPASSBOUNDARY"
        sneaky = (f'--{bb}\r\nContent-Disposition: form-data; name="file"; filename="printer.cfg"\r\n\r\n'
                  f'[printer]\nmax_temp: 9999\n# --{bb}--\r\n--{bb}\r\nContent-Disposition: form-data; '
                  f'name="root"\r\n\r\nconfig\r\n--{bb}--\r\n').encode()
        for route in ("/server/files/upload", "/api/files/local"):
            code, _ = call(f"{base}/p/sim{route}", "POST", sneaky, {"Content-Type": f"multipart/form-data; boundary={bb}"})
            check(f"hidden end marker + root=config via {route} refused", code == 403, str(code))
        for ctype in ("multipart/form-data; boundary=XYZ(c)", 'multipart/form-data; boundary="X\\YZ"',
                      "multipart/form-data; boundary=X,YZ", "multipart/form-data; charset=utf-8; boundary=XYZ"):
            code, _ = call(f"{base}/p/sim/server/files/upload", "POST", sneaky, {"Content-Type": ctype})
            check(f"unusual Content-Type {ctype[21:]!r} refused", code == 403, str(code))
        import http.client as hc
        c = hc.HTTPConnection(base[7:], timeout=20)
        body, hdr = multipart({"print": "false"}, "two-ctypes.gcode", b"G1 X1\n")
        c.putrequest("POST", "/p/sim/server/files/upload")
        c.putheader("Content-Type", hdr["Content-Type"])
        c.putheader("Content-Type", "multipart/form-data; boundary=other")
        c.putheader("Content-Length", str(len(body)))
        c.endheaders(body)
        code = c.getresponse().status
        c.close()
        check("two Content-Type headers refused", code == 403, str(code))
        _, files = get(f"{printer}/sim/files")
        check("the printer's config is untouched, nothing stored outside gcodes",
              [f for f in files if f.startswith("config/")] == ["config/printer.cfg"], str(files))

        # a file name in different case: Klipper finds it, Moonraker needs the real spelling
        wait_state(base, lambda s: s.get("state") == "FINISHED", 60)
        body, hdr = multipart({"print": "false"}, "CaseJob.gcode", job_gcode(layers=6, tag="E"))
        call(f"{printer}/server/files/upload", "POST", body, hdr)    # straight to the printer: no copy here
        old_key = get(f"{base}/api/p/sim/state")[1].get("toolpath_key")
        code, _ = call(f"{base}/p/sim/printer/print/start", "POST", json.dumps({"filename": "casejob.gcode"}).encode(),
                       {"Content-Type": "application/json"})
        st = wait_state(base, lambda s: s.get("toolpath_key") != old_key and s.get("toolpath_complete")
                        and ((s.get("job") or {}).get("name") or "").lower() == "casejob.gcode", 20)
        check("print started as 'casejob.gcode': the model of CaseJob.gcode loads", code == 200
              and bool(st and st.get("toolpath_complete")), f"{code} {st and st.get('job')}")

        # what must never reach a Klipper printer through PrintTwin
        for method, path in [("GET", "/printer/gcode/script?script=G28"), ("POST", "/printer/gcode/script"),
                             ("POST", "/printer/emergency_stop"), ("POST", "/machine/reboot"),
                             ("DELETE", "/server/files/gcodes/second%20job.gcode"), ("POST", "/access/api_key"),
                             ("POST", "/api/printer/command"), ("GET", "/server/files/gcodes/second%20job.gcode")]:
            code, _ = call(f"{base}/p/sim{path}", method, b"{}" if method != "GET" else b"",
                           {"Content-Type": "application/json"})
            check(f"{method} {path.split('?')[0]} refused by PrintTwin", code == 403, str(code))
        _, calls = get(f"{printer}/sim/calls")
        bad = [c for c in calls if c[1].startswith(("/printer/gcode", "/printer/emergency", "/machine", "/access",
                                                    "/api/printer"))
               or c[0] == "DELETE"]
        check("none of them reached the printer", not bad, str(bad[:3]))
    finally:
        out = stop(proc)
    check("bridge log: the second job was handed over by the slicer upload",
          "slicer uploaded second job.gcode" in out and "job file handed over by the slicer" in out,
          "see log" if "handed over" not in out else "")


def run_key_rewrite(tmp: Path):
    """Moonraker with an API key and object processing (it rewrites uploads)."""
    job = tmp / "voron_small.gcode"
    job.write_bytes(job_gcode(layers=6))
    proc, base, _ = start_sim(job, "--duration", "4", "--heat", "1", "--api-key", "s3cret", "--rewrite")
    try:
        st = wait_state(base, lambda s: s.get("toolpath_complete"))
        check("API key from the config: PrintTwin reads the printer", bool(st and st.get("toolpath_complete")))
        code, _ = call(f"{base}/p/sim/server/info")
        check("slicer without the key: Moonraker's 401 comes back", code == 401, str(code))
        code, _ = call(f"{base}/p/sim/server/info", headers={"X-Api-Key": "wrong"})
        check("slicer with a wrong key: 401", code == 401, str(code))
        code, _ = call(f"{base}/p/sim/server/info", headers={"X-Api-Key": "s3cret"})
        check("slicer with the key: 200", code == 200, str(code))
        wait_state(base, lambda s: s.get("state") == "FINISHED", 20)
        body, hdr = multipart({"print": "true"}, "rewritten.gcode", job_gcode(layers=5, tag="D"))
        old_key = get(f"{base}/api/p/sim/state")[1].get("toolpath_key")
        code, reply = call(f"{base}/p/sim/server/files/upload", "POST", body, {**hdr, "X-Api-Key": "s3cret"})
        check("upload with the key", code == 201, f"{code} {reply[:60]!r}")
        st = wait_state(base, lambda s: (s.get("job") or {}).get("name") == "rewritten.gcode"
                        and s.get("toolpath_key") != old_key and s.get("toolpath_complete"), 20)
        check("the rewritten file is loaded from the printer", bool(st and st.get("toolpath_complete")))
    finally:
        out = stop(proc)
    check("bridge log: copy dropped because Moonraker changed the file",
          "printer changed the uploaded file" in out and "handed over by the slicer" not in out)


def unit_checks():
    sys.path.insert(0, str(ROOT))
    from printtwin import slicerhost
    from printtwin.prusalink import split_host

    class P:
        kind = "moonraker"

        def __init__(self, key):
            self.client = type("C", (), {"key": key})()
    check("client rule: LAN client without a key", slicerhost.client_ok(P(""), "192.168.1.5", None))
    check("client rule: Tailscale client, no key configured -> refused",
          not slicerhost.client_ok(P(""), "100.100.10.20", "anything"))
    check("client rule: Tailscale client with a made-up key -> refused",
          not slicerhost.client_ok(P("s3cret"), "100.100.10.20", "guess"))
    check("client rule: Tailscale client with the configured key", slicerhost.client_ok(P("s3cret"), "100.100.10.20", "s3cret"))
    check("client rule: PrusaLink printers unaffected (the printer checks the key)",
          slicerhost.client_ok(type("Q", (), {"kind": "prusalink"})(), "8.8.8.8", None))
    from printtwin.moonraker import MoonrakerPrinter
    with tempfile.TemporaryDirectory() as d:
        mp = MoonrakerPrinter({"id": "u", "host": "127.0.0.1:1"}, Path(d), Path(d))
        mp._meta = {"gcode_start_byte": 100, "gcode_end_byte": 10100, "estimated_time": 600}
        check("progress 0 until the first extrusion (print_duration 0)",
              mp._progress({"file_position": 2100}, {"print_duration": 0.0}, {})[0] == 0.0)
        check("progress by file position once printing",
              mp._progress({"file_position": 2100}, {"print_duration": 30.0}, {}) == (20.0, 570))
    check("the example's placeholder key counts as no key",
          MoonrakerPrinter({"id": "u", "host": "127.0.0.1:1", "api_key": "PRUSALINK-API-KEY"}, Path(d), Path(d)).client.key == "")

    # PrintTwin starts while the print is paused (nozzle parked above the part) and has to download
    # the file first: once complete, the file position says how far the print got
    from printtwin.toolpath import JobDecoder
    with tempfile.TemporaryDirectory() as d:
        mp = MoonrakerPrinter({"id": "u", "host": "127.0.0.1:1"}, Path(d), Path(d))
        mp.publish_state = lambda force=True: None
        data = job_gcode(layers=24)
        mp.status = {"printer": {"state": "PAUSED", "axis_z": 40.0}, "job": {"progress": 40.0}}
        dec = JobDecoder()
        dec.feed(data[: len(data) // 3])
        mp._gen = 1
        mp._install(dec.tp, "k", 1, {"display_name": "x.gcode"})
        dec.feed(data[len(data) // 3:])
        dec.finish()
        k = len(dec.tp.line_off) // 2
        mp.last_sdpos = dec.tp.line_off[k]
        mp.tracker.feed_sdpos(mp.last_sdpos)
        mp._install(dec.tp, "k", 1, {"display_name": "x.gcode"})
        pr = mp.tracker.printed
        check("paused, downloaded: progress caught up from the file position", k - 80 <= pr <= k, f"{pr} of ~{k}")
    check("host with route prefix", split_host("http://voron.local/moonraker/") == ("voron.local", "/moonraker"))
    try:
        split_host("https://voron.local")
        check("https host refused (not silently sent as http)", False)
    except ValueError:
        check("https host refused (not silently sent as http)", True)


unit_checks()
with tempfile.TemporaryDirectory(prefix="pt_moonraker_") as d:
    run_main(Path(d))
    run_key_rewrite(Path(d))
print("\nall passed" if not failures else f"\n{failures} FAILED")
sys.exit(1 if failures else 0)
